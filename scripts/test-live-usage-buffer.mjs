import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/lib/liveUsageBuffer.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { mergeLiveUsage, clearLiveUsage } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const empty = () => ({ events: [], ignored: new Set() });
const event = (id, ts) => ({ id, occurred_at: ts, skill: 'example' });
const first = mergeLiveUsage(empty(), [event('a', 1), event('b', 2)]);
assert.deepEqual(first.events.map(e => e.id), ['b', 'a']);
assert.equal(mergeLiveUsage(first, [event('a', 1)]).events.length, 2);
const cleared = clearLiveUsage(first);
assert.equal(cleared.events.length, 0);
assert.equal(mergeLiveUsage(cleared, first.events).events.length, 0);
assert.deepEqual(mergeLiveUsage(cleared, [event('c', 3), event('a', 1)]).events.map(e => e.id), ['c']);
const capped = mergeLiveUsage(empty(), Array.from({ length: 250 }, (_, i) => event(String(i), i)));
assert.equal(capped.events.length, 200);
assert.equal(capped.events[0].id, '249');
assert.equal(capped.events.at(-1).id, '50');
assert.equal(first.events.length, 2);
assert.equal(empty().ignored.size, 0);
let repeated = empty();
for (let i = 0; i < 30; i++) repeated = clearLiveUsage(mergeLiveUsage(repeated, Array.from({ length: 100 }, (_, j) => event(`${i}:${j}`, i * 100 + j))));
assert.equal(repeated.ignored.size, 2000);
assert.equal(mergeLiveUsage(repeated, [event('29:99', 2999)]).events.length, 0);
console.log('12 live buffer checks passed');
