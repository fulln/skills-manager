import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const code = ts.transpileModule(fs.readFileSync(new URL('../src/lib/consoleSkill.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { consoleSkillCandidates: resolve } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const skill = (id, path, project_id = null) => ({ id, path, name: 'same', project_id });
const global = skill('global', '/global');
const local = skill('local', '/one/local', 'p1');
const other = skill('other', '/two/local', 'p2');
const snapshot = { projects: [{ id: 'p1', path: '/one' }, { id: 'p2', path: '/two' }], skills: [global, local, other] };
const event = project_path => ({ skill: 'same', project_path });
assert.deepEqual(resolve(event('/one'), snapshot).map(s => s.id), ['local']);
assert.deepEqual(resolve(event('/two'), snapshot).map(s => s.id), ['other']);
assert.deepEqual(resolve(event('/one/subdir'), snapshot).map(s => s.id), ['local']);
assert.deepEqual(resolve(event('/unknown'), snapshot).map(s => s.id), ['global']);
assert.deepEqual(resolve(event(null), snapshot).map(s => s.id), ['global']);
assert.equal(resolve({ skill: 'removed', project_path: '/one' }, snapshot).length, 0);
assert.equal(resolve(event('/one'), { ...snapshot, skills: [other] }).length, 0);
assert.equal(resolve(event('/one'), { ...snapshot, skills: [local, { ...local, id: 'alias' }] }).length, 1);
assert.equal(resolve(event('/one'), { ...snapshot, skills: [local, skill('variant', '/one/variant', 'p1')] }).length, 2);
assert.equal(resolve(event('/one/deep'), { projects: [...snapshot.projects, { id: 'nested', path: '/one/deep' }], skills: [...snapshot.skills, skill('nested', '/one/deep/local', 'nested')] })[0].id, 'nested');
console.log('10 skill resolution checks passed');
