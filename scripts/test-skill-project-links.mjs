import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/skillProjectLinks.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports });
const build = exports.skillProjectLinks;
const skill = { id: 'central', name: 'design', central_path: '/library/design' };
const projects = [{ id: 'a', name: 'Alpha', path: '/work/a', effective_skill_ids: ['central'] }, { id: 'b', name: 'Beta', path: '/work/b' }];
const snap = { projects, skills: [{ id: 'central', name: 'design', project_id: null, path: '/library/design', scope: 'global' }] };
assert.equal(build(skill, snap, [], []).length, 0, 'Global availability must not mark every project as associated');
snap.skills.push({ id: 'copy', name: 'design', project_id: 'b', path: '/work/b/.agents/skills/design' });
snap.skills.push({ id: 'mirror', name: 'design', project_id: 'b', canonical_path: '/library/design', path: '/work/b/.codex/skills/design' });
snap.skills.push({ id: 'other', name: 'unrelated', project_id: 'a', path: '/x' });
const scopes = [{ id: 'scope-a', kind: 'project', project_path: '/work/a', name: 'Alpha' }];
const row = { skill: 'design', window_days: 30, project: 'scope-a', events: 4, explicit: 2, declared: 1, inferred: 1 };
const rows = [row, { ...row, window_days: 7 }, { ...row, skill: 'other' }, { ...row, project: null }, { ...row, project: 'unknown-scope' }, { ...row, project: '/work/b', explicit: 1 }];
const links = build(skill, snap, scopes, rows);
assert.equal(links.length, 2);
assert.equal(links[0].name, 'Alpha');
assert.equal(links[0].explicit, 2, 'Only the 30-day window is counted');
assert.equal(links[0].inferred, 1);
assert.equal(links[1].local, true, 'Canonical match identifies same skill');
assert.equal(links[1].sameName, true, 'Distinct project copy is labelled, not conflated with central identity');
assert.equal(links[1].explicit, 1, 'Absolute project paths also resolve');
const unknown = build(skill, { projects: [], skills: [] }, [], [{ ...row, project: '/archive/legacy' }]);
assert.equal(unknown[0].name, 'legacy');
assert.equal(unknown[0].path, '/archive/legacy');
const source = fs.readFileSync('src/components/SkillProjectLinks.tsx', 'utf8');
assert.ok(source.includes('Promise.allSettled'), 'Partial source failures remain visible');
assert.ok(source.includes('cancelled = true'), 'Closing/changing detail invalidates stale responses');
assert.ok(source.includes('aria-expanded={expanded}') && source.includes('aria-controls={id}'));
console.log('Project association checks passed: global availability, exact copies, name-only copies, scope/path mapping, time windows, evidence distinctions, partial failures and cancellation.');
