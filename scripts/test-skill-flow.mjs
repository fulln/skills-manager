import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ts from 'typescript';
const file = new URL('../src/components/SkillUsageFlow.tsx', import.meta.url);
const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React } }).outputText;
const exports = {};
const require = id => {
  if (!id.startsWith('.')) return createRequire(file)(id);
  const url = new URL(id + '.ts', file);
  const mod = {};
  const text = ts.transpileModule(fs.readFileSync(url, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
  vm.runInNewContext('(function(require,exports){' + text + '\n})')(createRequire(url), mod);
  return mod;
};
vm.runInNewContext('(function(require,exports,React){' + code + '\n})')(require, exports, React);
const { SkillUsageFlow } = exports;
const render = event => renderToStaticMarkup(React.createElement(SkillUsageFlow, { event }));
const event = { id: 'actual', agent: 'codex', project_path: '/Users/a/project/', skill: 'test-skill', evidence: 'explicit_invocation', occurred_at: 10, source_ref: '/a/log:15', session_id: 's', excerpt: 'safe excerpt' };
const actual = render(event);
assert.match(actual, /Codex/);
assert.match(actual, />project<\/p>/);
assert.match(actual, /title="\/Users\/a\/project\/"/);
assert.match(actual, /test-skill/);
assert.match(actual, /明确调用/);
assert.doesNotMatch(actual, /success|成功|gpt-|magpie/);
assert.match(render({ ...event, agent: null, project_path: null }), /未知 Agent/);
assert.match(render({ ...event, agent: null, project_path: null }), /未归属项目/);
assert.match(render({ ...event, evidence: 'read_inferred' }), /读取说明/);
assert.doesNotMatch(render({ ...event, evidence: 'read_inferred' }), /明确调用/);
assert.match(render({ ...event, evidence: 'assistant_declaration' }), /声明使用/);
assert.match(render(null), /等待真实技能事件/);
assert.doesNotMatch(render(null), /Codex|test-skill/);
assert.match(render({ ...event, skill: '<script>bad</script>' }), /&lt;script&gt;bad&lt;\/script&gt;/);
assert.doesNotMatch(actual, /safe excerpt|\/a\/log:15/);
console.log('15 skill flow rendering checks passed');
